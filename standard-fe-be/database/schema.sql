-- DDL Script: Master Produk dan Transaksi Produk
-- Database: Microsoft SQL Server
-- =====================================================================

-- 1. Tabel Master Produk (PRODUCT_MST)
IF NOT EXISTS (SELECT * FROM sys.tables WHERE name = 'PRODUCT_MST')
BEGIN
    CREATE TABLE PRODUCT_MST (
        PRODUCT_ID INT IDENTITY(1,1) NOT NULL,
        PRODUCT_NAME VARCHAR(150) NOT NULL,
        DESCRIPTION VARCHAR(500) NULL,
        PRICE DECIMAL(18,2) NOT NULL,
        STOCK INT NOT NULL,
        IS_ACTIVE BIT NOT NULL CONSTRAINT DF_PRODUCT_MST_IS_ACTIVE DEFAULT (1),
        CREATED_AT DATETIME2 NOT NULL CONSTRAINT DF_PRODUCT_MST_CREATED_AT DEFAULT (SYSUTCDATETIME()),
        UPDATED_AT DATETIME2 NOT NULL CONSTRAINT DF_PRODUCT_MST_UPDATED_AT DEFAULT (SYSUTCDATETIME()),
        CONSTRAINT PK_PRODUCT_MST PRIMARY KEY CLUSTERED (PRODUCT_ID ASC),
        CONSTRAINT CK_PRODUCT_MST_STOCK CHECK (STOCK >= 0),
        CONSTRAINT CK_PRODUCT_MST_PRICE CHECK (PRICE >= 0)
    );
END
GO

-- 2. Tabel Transaksi Produk (PRODUCT_TRX)
IF NOT EXISTS (SELECT * FROM sys.tables WHERE name = 'PRODUCT_TRX')
BEGIN
    CREATE TABLE PRODUCT_TRX (
        TRANSACTION_ID BIGINT IDENTITY(1,1) NOT NULL,
        TRANSACTION_CODE VARCHAR(50) NOT NULL,
        PRODUCT_ID INT NOT NULL,
        TRANSACTION_DATE DATETIME2 NOT NULL CONSTRAINT DF_PRODUCT_TRX_DATE DEFAULT (SYSUTCDATETIME()),
        QUANTITY INT NOT NULL,
        TOTAL_AMOUNT DECIMAL(18,2) NOT NULL,
        CREATED_AT DATETIME2 NOT NULL CONSTRAINT DF_PRODUCT_TRX_CREATED_AT DEFAULT (SYSUTCDATETIME()),
        CONSTRAINT PK_PRODUCT_TRX PRIMARY KEY CLUSTERED (TRANSACTION_ID ASC),
        CONSTRAINT UQ_PRODUCT_TRX_CODE UNIQUE (TRANSACTION_CODE),
        CONSTRAINT FK_PRODUCT_TRX_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT_MST (PRODUCT_ID),
        CONSTRAINT CK_PRODUCT_TRX_QUANTITY CHECK (QUANTITY > 0),
        CONSTRAINT CK_PRODUCT_TRX_AMOUNT CHECK (TOTAL_AMOUNT >= 0)
    );
END
GO
